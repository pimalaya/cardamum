//! # Account commands
//!
//! Dispatches the account subcommands, which read the configuration
//! rather than an already built client.

use std::path::PathBuf;

use anyhow::Result;
use clap::Subcommand;
use pimalaya_cli::printer::Printer;

use crate::{
    account::{
        capability::AccountCapabilityCommand, check::AccountCheckCommand, list::AccountListCommand,
    },
    backend::Backend,
};

/// Manage accounts defined in the TOML configuration file.
///
/// An account is a named group of backend settings, which these
/// subcommands inspect or validate. To create one, add an
/// `[accounts.<name>]` table to the configuration file.
#[derive(Debug, Subcommand)]
pub enum AccountCommand {
    #[command(visible_alias = "ls")]
    List(AccountListCommand),
    Check(AccountCheckCommand),
    #[command(alias = "capabilities")]
    Capability(AccountCapabilityCommand),
}

impl AccountCommand {
    pub fn execute(
        self,
        printer: &mut impl Printer,
        config_paths: &[PathBuf],
        account_name: Option<&str>,
        backend: Backend,
    ) -> Result<()> {
        match self {
            Self::List(cmd) => cmd.execute(printer, config_paths),
            Self::Check(cmd) => cmd.execute(printer, config_paths, account_name, backend),
            Self::Capability(cmd) => cmd.execute(printer, config_paths, account_name, backend),
        }
    }
}
